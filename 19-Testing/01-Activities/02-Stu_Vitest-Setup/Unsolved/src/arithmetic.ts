export default class Arithmetic {

  // A function named sum is created that takes two numbers and returns the sum of the two numbers.
  sum(a: number, b: number) : number {
    return a + b;
  }

  difference(a: number, b: number) : number {
    return a - b;
  }

  product(a: number, b: number) : number {
    return a * b;
  }

  quotient(a: number, b: number) : number {
    return a / b;
  }
};
